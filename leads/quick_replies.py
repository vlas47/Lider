def build_quick_replies(lead) -> list[dict]:
    selected = suggested_topic(lead)
    return [
        {
            "id": topic["id"],
            "label": topic["label"],
            "reply": contextual_reply(topic, lead),
            "suggested": topic["id"] == selected["id"],
        }
        for topic in TOPICS
    ]


def build_suggested_quick_reply(lead) -> dict:
    topic = suggested_topic(lead)
    return {
        "id": topic["id"],
        "label": topic["label"],
        "reply": contextual_reply(topic, lead),
        "suggested": True,
    }
