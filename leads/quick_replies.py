PRIORITY = ("bots", "ecommerce", "corporate", "landing", "wms", "crm", "integrations", "web-app", "automation", "site-work")


def _source_text(lead) -> str:
    return f"{getattr(lead, 'title', '')} {getattr(lead, 'raw_text', '')}".lower()


def _topic(topic_id: str):
    return next((topic for topic in TOPICS if topic["id"] == topic_id), None)


def suggested_topic(lead):
    text = _source_text(lead)
    for topic_id in PRIORITY:
        topic = _topic(topic_id)
        if topic and any(keyword in text for keyword in topic["keywords"]):
            return topic
    return _topic("site-work")


